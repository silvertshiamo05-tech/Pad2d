#!/usr/bin/env bash
# Checks the Swift port against the original Inochi2D 0.8.7 runtime.
#
# Needs: ldc2 + dub (LDC >= 1.41), swift, python3, git, curl.
# Builds Inochi2D 0.8.7 in its "renderless" configuration (no GPU needed),
# then compares every drawn vertex of the sample models across rest pose,
# parameter poses and physics simulation. Fails if anything differs by more
# than 0.05 px.
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p build

if [ ! -d build/inochi2d ]; then
  git clone -q --depth 1 --branch v0.8.7 https://github.com/Inochi2D/inochi2d build/inochi2d
  # The version file is generated by a git tool; it's already committed, so skip it.
  sed -i.bak '/preBuildCommands/d' build/inochi2d/dub.sdl
  # 0.8.7's renderless configuration misses three no-op mask hooks.
  cat >> build/inochi2d/source/inochi2d/core/nodes/drawable.d <<'D'

version (InRenderless) {
    void inBeginMask(bool hasMasks) { }
    void inEndMask() { }
    void inBeginMaskContent() { }
}
D
fi

../../scripts/fetch-sample-models.sh >/dev/null
models=../../App/Resources/Models

(cd reference && dub build --build=release -q)
(cd port && swift build -c release -q)
ref=reference/inochi2d-reference
port=port/.build/release/port

status=0
check() {
  local m=$1; shift
  "$ref" "$models/$m.inx" "$@" > build/ref.txt
  "$port" "$models/$m.inx" "$@" > build/port.txt
  python3 compare.py build/ref.txt build/port.txt "$m $*" | tee -a build/report.txt
  grep -q "mismatched=0 " <(tail -1 build/report.txt) || status=1
}
: > build/report.txt
for m in Aka Midori; do
  check $m rest
  check $m params
  check $m params "Head:: Yaw-Pitch" 1,1
  check $m params "Head:: Yaw-Pitch" -0.7,0.4
  check $m params "Body:: Roll" 0.6
  check $m params "Mouth:: Shape" 0.3,0.8
  check $m params "Eye:: Left:: Blink" 0.7
  check $m params "Breath" 0.5
  FRAMES=30 check $m physics
  FRAMES=600 check $m physics
  FRAMES=200 check $m physics "Head:: Yaw-Pitch" 1,0.5
done
exit $status
